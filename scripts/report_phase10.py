"""Phase 10 blocks of FINDINGS.md (used by report.py): Phase 10 report and section 8 (Manuscript Numbers Sheet + Methods Facts Sheet)."""
from __future__ import annotations

import csv
import json
import xml.etree.ElementTree as ET
from pathlib import Path

from report import md_table, rel


def rd(p: Path) -> list[dict]:
    return list(csv.DictReader(p.open(encoding="utf-8")))


def esc(s: str) -> str:
    return s.replace("|", "/").replace("\n", " ")


def numbers_block(run: Path) -> tuple[str, list[list]]:
    nums, meth = rd(run / "numbers_sheet.csv"), rd(run / "methods_facts.csv")
    L = [f"Generated by `scripts/run_phase10.py` (run `{run.name}`) from the artifacts; every row names the artifact it was read from, and the table is re-rendered and verified by `scripts/check_numbers.py`. "
         "Values are formatted as 'a / b / c' in the order named in the quantity; CIs are 95% (bootstrap). Chapter sections follow plan section 7.", "",
         f"### 8a. Manuscript Numbers Sheet ({len(nums)} entries; `{rel(run / 'numbers_sheet.csv')}`)", "",
         md_table(["ID", "Sec.", "Quantity", "Value", "Artifact", "Note"], [[r["id"], r["chapter_section"], esc(r["quantity"]), esc(r["value"]), f"`{r['artifact']}`", esc(r["note"])] for r in nums]), "",
         f"### 8b. Methods Facts Sheet (`{rel(run / 'methods_facts.csv')}`)", "",
         md_table(["ID", "Sec.", "Parameter", "Value", "Artifact"], [[r["id"], r["chapter_section"], esc(r["quantity"]), esc(r["value"]), f"`{r['artifact']}`"] for r in meth]), ""]
    return "\n".join(L), [["P10-1", 10, f"Manuscript Numbers Sheet: {len(nums)} entries, Methods Facts Sheet: {len(meth)} entries", rel(run / "numbers_sheet.csv")]]


def phase10_block(run: Path) -> tuple[str, list[list]]:
    idx: list[list] = []
    claims = rd(run / "claims.csv")
    figs = rd(run / "figure_inventory.csv")
    arch = json.loads((run / "archive_info.json").read_text(encoding="utf-8"))
    ok = sum(f["png_exists"] == "True" and f["csv_exists"] == "True" for f in figs)
    L = [f"Run `{run.name}` - manifest: `{rel(run / 'run_manifest.json')}`. Documentation and handoff only; nothing was measured.", "",
         f"- **README** (task 10.1): `README.md` (purpose, architecture diagram, setup, run commands, repository map, how to read this file).",
         f"- **Figures** (task 10.2): {ok} of {len(figs)} figures exist as 300-dpi PNG with a backing CSV (`{rel(run / 'figure_inventory.csv')}`); style: one palette, labelled axes, CIs where applicable.",
         "- **Numbers and methods sheets** (task 10.3): section 8 of this file.",
         f"- **Source notes** (task 10.4): `docs/manuscript_source_notes.md` (artifact -> chapter section map; {sum(c['status'] == 'supported' for c in claims)} claims the data supports, {sum(c['status'] == 'not_supported' for c in claims)} it does not; list in `{rel(run / 'claims.csv')}`).",
         "- **Seminar assets** (task 10.5): `docs/seminar_summary.md` (one page) and `docs/seminar/` (8 figures with data).",
         f"- **Archive** (task 10.6): `{arch['archive']}`, {arch['files']} files, {arch['bytes'] / 1e6:.1f} MB. Tag `v1.0-manuscript-ref` is created by the human after the Phase 10 commit.", ""]
    idx.append(["P10-2", 10, f"Handoff: {ok}/{len(figs)} figures with CSV; {len(claims)} claims listed; archive {arch['bytes'] / 1e6:.1f} MB", rel(run / "claims.csv")])
    L += ["**Claims the data supports / does not support** (excerpt; full text in `docs/manuscript_source_notes.md`):", "",
          md_table(["Status", "Area", "Claim", "Strength"], [[c["status"].replace("_", " "), c["area"], esc(c["claim"]), esc(c["strength"])] for c in claims]), ""]
    na = run / "number_audit.json"
    if na.exists():
        n = json.loads(na.read_text(encoding="utf-8"))
        L += [f"**Final numbers audit** (`{rel(na)}`, `scripts/check_numbers.py`, including section 8): {n['generated_blocks_checked']} generated blocks re-rendered from the artifacts, not reproducible: {n['generated_blocks_not_reproducible'] or 'none'}; "
              f"{n['artifact_paths_checked']} quoted artifact paths, missing: {n['missing_paths'] or 'none'}; {len(n['unflagged_hand_numbers'])} unlabelled hand-typed numbers. Passed: **{n['passed']}**.", ""]
        idx.append(["P10-4", 10, f"Final numbers audit passed: {n['passed']}", rel(na)])
    xml = run / "pytest_junit.xml"
    if xml.exists():
        r = ET.parse(xml).getroot()
        ts = r if r.tag == "testsuite" else r.find("testsuite")
        tot, fail, err, skip = (int(ts.get(x, 0)) for x in ("tests", "failures", "errors", "skipped"))
        L += [f"**pytest** (whole suite at Phase 10 exit): {tot} tests, {fail} failures, {err} errors, {skip} skipped (`{rel(xml)}`).", ""]
        idx.append(["P10-3", 10, f"pytest: {tot - fail - err - skip}/{tot} passed", rel(xml)])
    L += ["**Manuscript hook**: all sections; the human writes the prose from sections 3 and 8 of this file and the source notes. No manuscript text was generated.", ""]
    return "\n".join(L), idx
